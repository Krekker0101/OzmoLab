/**
 * Type-safe translation lookup with parameter interpolation support
 * e.g. t(lesson.step, ru, { current: 1, total: 3 })
 */
export function t(
  key: string,
  lang: SupportedLanguage = 'tg',
  params?: Record<string, string | number>
): string {
  const dictionary = translations[lang] || translations.tg;
  let text = dictionary[key];

  if (!text) {
    // Fallback to alternative language if key is missing
    const fallbackDictionary = lang === 'en' ? translations.ru : lang === 'tg' ? translations.ru : translations.tg;
    text = fallbackDictionary[key] || key;
  }

  if (params) {
    Object.entries(params).forEach(([paramKey, paramValue]) => {
      text = text.replace(new RegExp(`{${paramKey}}`, 'g'), String(paramValue));
    });
  }

  return text;
}
