import {GlossaryTerm, SupportedLanguage} from '../../shared/types.ts';
import glossary from '../../shared/glossary.json';

/**
 * Формирует компактную терминологическую таблицу из glossary.json для внедрения в промпт.
 */
function formatGlossaryForPrompt(): string {
  const terms = glossary as GlossaryTerm[];
  return terms
    .map(
      (t) =>
        `- ${t.term_tg} = ${t.term_ru} (аломат: ${t.symbol || '-'}, воҳид: ${t.unit || '-'})`
    )
    .join('\n');
}

